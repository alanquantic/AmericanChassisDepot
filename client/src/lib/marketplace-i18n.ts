export function t(key: keyof typeof marketplaceTranslations.en): string {
  const lang = getCurrentLanguage() as 'en' | 'es';
  const translations = marketplaceTranslations[lang] || marketplaceTranslations.en;
  return translations[key] || key;
}

export function formatPrice(price: number | string): string {
  const numPrice = typeof price === 'string' ? parseFloat(price) : price;
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(numPrice);
}

export function formatDate(date: string | Date): string {
  const lang = getCurrentLanguage();
  return new Intl.DateTimeFormat(lang === 'es' ? 'es-ES' : 'en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  }).format(new Date(date));
}

export function getLocalizedField<T extends { [key: string]: any }>(
  item: T,
  field: string
): string {
  const lang = getCurrentLanguage();
  if (lang === 'es') {
    const esField = `${field}Es` as keyof T;
    if (item[esField]) {
      return item[esField] as string;
    }
  }
  return item[field as keyof T] as string || '';
}
